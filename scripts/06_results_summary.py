"""Collect every result CSV into reports/RESULTS.md (tables for the technical report).

Nothing here is typed by hand: all numbers are read from files produced by scripts 01-05.
"""
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from pathsnap import config  # noqa: E402

R = config.REPORTS


def md(df, floatfmt=".4f"):
    return df.to_markdown(index=False, floatfmt=floatfmt)


def plot_evaluator(ev):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    fig, ax = plt.subplots(1, 2, figsize=(13, 4))
    x = np.arange(len(ev))
    for a, k, t in ((ax[0], "accuracy", "Pointwise accuracy"), (ax[1], "route_continuity", "Route continuity")):
        a.bar(x - 0.2, ev[f"clf_{k}"], 0.4, label="classifier only")
        a.bar(x + 0.2, ev[f"hmm_{k}"], 0.4, label="classifier + HMM")
        a.set_xticks(x, ev.trip_id, rotation=45); a.set_ylim(0.75, 1.0)
        a.set_title(f"{t} per evaluator-test trip (via API)"); a.legend()
    fig.tight_layout(); fig.savefig(os.path.join(config.FIGURES, "eval_hmm_vs_classifier.png"), dpi=120); plt.close(fig)


def main():
    out = ["# PathSnap – results summary", "",
           "_Auto-generated by `scripts/06_results_summary.py` from the CSV files in `reports/`._", ""]

    s = pd.read_csv(os.path.join(R, "eda", "summary_by_partition.csv"))
    out += ["## 1. Dataset (train + student_test)", "", md(s, ".3f"), ""]
    for p in ("train", "student_test"):
        c = pd.read_csv(os.path.join(R, f"candidate_stats_{p}.csv"))
        miss = (c.candidate_miss_rate * c.n_obs).sum() / c.n_obs.sum()
        out.append(f"- **{p}**: {c.n_obs.sum()} observations, {c.n_rows.sum()} candidate rows, "
                   f"candidate miss rate {miss:.4f}, median GPS-to-reference distance "
                   f"{c.label_dist_median.median():.2f} m, unreliable-label share "
                   f"{(c.unreliable_label_frac * c.n_obs).sum() / c.n_obs.sum():.4f}")
    out.append("")

    cmp = pd.read_csv(os.path.join(R, "model_comparison.csv")).sort_values("cv_top1", ascending=False)
    cols = ["model", "family", "config", "cv_macro_f1", "cv_macro_f1_std", "cv_top1", "train_macro_f1",
            "test_top1", "test_macro_f1", "test_precision_macro", "test_recall_macro", "test_log_loss",
            "route_continuity", "train_time_s", "inference_ms_per_1k_rows"]
    out += ["## 2. Model comparison", "",
            "CV = 5-fold GroupKFold over the 80 training trips (groups = trips). Test = 10 student-test trips. "
            "Macro F1 / log loss are candidate-level (binary: is this the reference arc); Top-1 is "
            "observation-level (highest-scoring candidate == reference arc, observations without the "
            "reference among candidates count as errors on test); route continuity is for classifier-only "
            "top-1 predictions.", "", md(cmp[cols]), ""]

    sp = json.load(open(os.path.join(R, "bayes_opt_search_space.json")))
    tv = pd.read_csv(os.path.join(R, "tuned_vs_untuned.csv"))
    out += ["## 3. Bayesian optimisation (LightGBM, Optuna TPE)", "",
            f"- Objective: {sp['objective']}; trials: {sp['n_trials']}; search time: {sp['search_seconds']:.0f} s",
            f"- Best objective value: {sp['best_value']:.4f}",
            "- Search space: `" + json.dumps(sp["search_space"]) + "`",
            "- Best parameters: `" + json.dumps(sp["best_params"]) + "`", "", md(tv), ""]

    hs = pd.read_csv(os.path.join(R, "hmm_summary.csv"))
    hv = pd.read_csv(os.path.join(R, "hmm_vs_classifier.csv"), dtype={"trip_id": str})
    ht = pd.read_csv(os.path.join(R, "hmm_tuning.csv"))
    cfg = json.load(open(os.path.join(config.ARTIFACTS, "hmm_config.json")))
    out += ["## 4. HMM / Viterbi decoding", "",
            f"Decoder configuration: `{json.dumps({k: v for k, v in cfg.items() if k != 'tuned_on'})}`", "",
            "### Decoder tuning (12 held-out training trips)", "", md(ht), "",
            "### Classifier-only vs classifier + HMM (student_test)", "", md(hs), "",
            "### Per trip", "",
            md(hv[["trip_id", "n_obs", "clf_accuracy", "hmm_accuracy", "clf_route_continuity",
                   "hmm_route_continuity", "clf_route_f1", "hmm_route_f1", "hmm_breaks", "time_total_s"]]), ""]

    ev_dir = os.path.join(R, "evaluator_test")
    if os.path.exists(os.path.join(ev_dir, "results.csv")):   # written by scripts/07_evaluator_run.py
        ev = pd.read_csv(os.path.join(ev_dir, "results.csv"), dtype={"trip_id": str})
        es = json.load(open(os.path.join(ev_dir, "summary.json")))
        plot_evaluator(ev)
        out += ["## 5. Final evaluation: 10 evaluator-test trips (via the API)", "",
                f"Run {es['run_time']} through `POST /predict`; model checksum `{es['final_model_sha256_16']}`, "
                f"decoder checksum `{es['hmm_config_sha256_16']}` (frozen; nothing tuned on these trips).", "",
                f"- Pointwise accuracy (observation-weighted): classifier {es['clf_accuracy_obs_weighted']:.4f} -> "
                f"HMM **{es['hmm_accuracy_obs_weighted']:.4f}**",
                f"- Route continuity (trip mean): {es['clf_route_continuity_mean']:.4f} -> **{es['hmm_route_continuity_mean']:.4f}**",
                f"- Route F1 (trip mean): {es['clf_route_f1_mean']:.4f} -> **{es['hmm_route_f1_mean']:.4f}**",
                f"- Trips with HMM accuracy >= 95%: {es['trips_hmm_acc_ge_95']}/10; HMM better than classifier on "
                f"{es['trips_where_hmm_beats_classifier']}/10 trips; total server time {es['server_time_s_total']:.1f} s", "",
                md(ev[["trip_id", "n_obs", "clf_accuracy", "hmm_accuracy", "clf_route_continuity", "hmm_route_continuity",
                       "clf_route_f1", "hmm_route_f1", "hmm_breaks", "server_time_s"]]), ""]

    out += ["## 6. Figures and maps", ""]
    for f in sorted(os.listdir(config.FIGURES)):
        out.append(f"- `reports/figures/{f}`")
    for f in sorted(os.listdir(config.MAPS)):
        out.append(f"- `reports/maps/{f}` (interactive Folium)")
    with open(os.path.join(R, "RESULTS.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
